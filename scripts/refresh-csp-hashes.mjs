// Computes CSP hashes for the inline scripts and style attributes that Astro's
// security.csp cannot track automatically (Starlight's `is:inline` scripts and
// framework style attributes) and writes them to src/csp-hashes.json.
//
// Run `npm run build` (which builds, refreshes, and rebuilds) after upgrading
// Astro/Starlight. tests/e2e/navigation.spec.ts fails on any drift, so a stale
// hash file can never pass CI silently.
import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { createHash } from "node:crypto";
import { resolve, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(fileURLToPath(new URL("..", import.meta.url)));
const dist = join(root, "dist");
const outFile = join(root, "src", "csp-hashes.json");

const decode = (s) =>
  s
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&#0?39;/g, "'")
    .replace(/&amp;/g, "&");

const sha256 = (content) => `sha256-${createHash("sha256").update(content).digest("base64")}`;

function listHtmlFiles(dir, base = "") {
  const out = [];
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const rel = base ? `${base}/${e.name}` : e.name;
    if (e.isDirectory()) out.push(...listHtmlFiles(join(dir, e.name), rel));
    else if (e.name.endsWith(".html")) out.push(rel);
  }
  return out;
}

const scriptHashes = new Set();
const styleAttrHashes = new Set();

for (const rel of listHtmlFiles(dist)) {
  const html = readFileSync(join(dist, rel), "utf8");
  const meta = html.match(/http-equiv="content-security-policy" content="([^"]*)"/i);
  const allowed = new Set(
    meta ? [...meta[1].matchAll(/'sha256-([^']+)'/g)].map((m) => m[1]) : []
  );

  for (const m of html.matchAll(/<script(?![^>]*\ssrc=)[^>]*>([\s\S]*?)<\/script>/g)) {
    const content = decode(m[1]);
    const hash = sha256(content).slice("sha256-".length);
    if (!allowed.has(hash)) scriptHashes.add(`sha256-${hash}`);
  }

  for (const m of html.matchAll(/style="([^"]*)"/g)) {
    const value = decode(m[1]);
    styleAttrHashes.add(sha256(value));
  }
}

const prev = (() => {
  try {
    return JSON.parse(readFileSync(outFile, "utf8"));
  } catch {
    return { scriptHashes: [], styleAttrHashes: [] };
  }
})();

// Union, not replace: once a hash is needed it stays, so the two-pass build
// (build → refresh → build) converges instead of oscillating.
const scriptHashesAll = new Set([...prev.scriptHashes ?? [], ...scriptHashes]);
const styleAttrHashesAll = new Set([...prev.styleAttrHashes ?? [], ...styleAttrHashes]);

const next = {
  _comment:
    "Generated by scripts/refresh-csp-hashes.mjs. Do not edit by hand; run npm run build after framework upgrades.",
  scriptHashes: [...scriptHashesAll].sort(),
  styleAttrHashes: [...styleAttrHashesAll].sort(),
};

writeFileSync(outFile, JSON.stringify(next, null, 2) + "\n");
console.log(
  `csp-hashes: ${next.scriptHashes.length} script hashes, ${next.styleAttrHashes.length} style-attr hashes${next.scriptHashes.length || next.styleAttrHashes.length ? " (rebuild required)" : ""}`
);
